"""Pre-record reverse-process frames with the same code path as the live server, so the demo has an
identical offline fallback (app/assets/data/replay.js)."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "app"))
import json  # noqa: E402

from server import generate_frames  # noqa: E402

OUT = os.path.join(os.path.dirname(HERE), "app", "assets", "data", "replay.js")
CONFIGS = [
    ("cifar", 50, "learned"), ("cifar", 50, "fixed_large"),
    ("cifar", 10, "learned"), ("cifar", 10, "fixed_large"),
    ("cifar", 250, "learned"), ("cifar", 250, "fixed_large"),
]

if __name__ == "__main__":
    data = {}
    for model, K, var in CONFIGS:
        frames = list(generate_frames(model, K, var, seed=0, n=4, max_frames=30))
        data[f"{model}_K{K}_{var}"] = frames
        print(model, K, var, len(frames), "frames,", frames[-1]["elapsed"], "s")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("/* generated by scripts/04_record_replay.py */\nwindow.REPLAY = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print("wrote", OUT, os.path.getsize(OUT) / 1e6, "MB")
