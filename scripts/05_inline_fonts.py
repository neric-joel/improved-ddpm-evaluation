"""Embed web fonts as data URIs so the demo page renders correctly when opened straight from disk (file://).
Chrome/Edge refuse to load font files over file://, but accept data-URI fonts inside a stylesheet.

Writes, for each app:  assets/css/fonts.css  and  assets/katex/katex.inline.css
"""
import base64
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APPS = [ROOT / "app"]

FACES = [
    # family, file, weight range, unicode-range (None = all), style
    ("Source Serif 4", "source-serif-4-latin-wght-normal.woff2", "200 900", "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+2074, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD", "normal"),
    ("Source Serif 4", "source-serif-4-latin-wght-italic.woff2", "200 900", "U+0000-00FF, U+2000-206F", "italic"),
    ("Source Serif 4", "source-serif-4-latin-ext-wght-normal.woff2", "200 900", "U+0100-02AF, U+1E00-1E9F, U+2020, U+20A0-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF", "normal"),
    ("Source Serif 4", "source-serif-4-greek-wght-normal.woff2", "200 900", "U+0370-03FF", "normal"),
    ("Source Sans 3", "source-sans-3-latin-wght-normal.woff2", "200 900", "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+2074, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD", "normal"),
    ("Source Sans 3", "source-sans-3-latin-ext-wght-normal.woff2", "200 900", "U+0100-02AF, U+1E00-1E9F, U+2020, U+20A0-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF", "normal"),
    ("Source Sans 3", "source-sans-3-greek-wght-normal.woff2", "200 900", "U+0370-03FF", "normal"),
    ("Source Sans 3", "source-sans-3-greek-ext-wght-normal.woff2", "200 900", "U+1F00-1FFF", "normal"),
]


def b64(p):
    return base64.b64encode(p.read_bytes()).decode()


for app in APPS:
    fonts = app / "assets" / "fonts"
    css = ["/* generated by scripts/05_inline_fonts.py: fonts embedded so file:// works */"]
    for fam, f, w, ur, style in FACES:
        rule = f'@font-face {{ font-family: "{fam}"; src: url(data:font/woff2;base64,{b64(fonts / f)}) format("woff2"); font-weight: {w}; font-style: {style}; font-display: swap;'
        if ur:
            rule += f" unicode-range: {ur};"
        css.append(rule + " }")
    (app / "assets" / "css" / "fonts.css").write_text("\n".join(css) + "\n", encoding="utf-8")

    kdir = app / "assets" / "katex"
    if not (kdir / "katex.min.css").exists():
        print(app.name, "fonts.css", round((app / "assets/css/fonts.css").stat().st_size / 1e3), "KB (no KaTeX)")
        continue
    kcss = (kdir / "katex.min.css").read_text(encoding="utf-8")

    def repl(m):
        name = m.group(1)
        return f'src:url(data:font/woff2;base64,{b64(kdir / "fonts" / (name + ".woff2"))}) format("woff2")'

    kcss = re.sub(r'src:url\(fonts/([A-Za-z0-9_\-]+)\.woff2\) format\("woff2"\)(,url\([^)]*\) format\("[a-z]+"\))*', repl, kcss)
    (kdir / "katex.inline.css").write_text(kcss, encoding="utf-8")
    print(app.name, "fonts.css", round((app / "assets/css/fonts.css").stat().st_size / 1e3), "KB; katex.inline.css", round((kdir / "katex.inline.css").stat().st_size / 1e3), "KB")
